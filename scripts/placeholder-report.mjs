// Collects every visible [PLACEHOLDER] from dist/, grouped by page, and writes it into README.md
// between the PLACEHOLDERS:START / PLACEHOLDERS:END markers. Run after `npm run build`.
import { readFileSync, writeFileSync } from 'node:fs';
import { htmlFiles, urlPath, read } from './lib.mjs';

const decode = (s) => s.replace(/&amp;/g, '&').replace(/&lt;/g, '<').replace(/&gt;/g, '>').replace(/&quot;/g, '"').replace(/&#39;/g, "'");
const LEGEND = '[PLACEHOLDER: …]';

const perPage = new Map();
const visible = new Set();
const inJsonLd = new Set();
for (const file of htmlFiles()) {
  const html = read(file);
  const found = new Set();
  for (const m of [...html.matchAll(/<mark class="ph"[^>]*>([^<]+)<\/mark>/g)]) {
    const t = decode(m[1]);
    if (t === LEGEND) continue;
    found.add(t);
  }
  found.forEach((t) => visible.add(t));
  perPage.set(urlPath(file), found);
  for (const m of html.matchAll(/<script type="application\/ld\+json">([\s\S]*?)<\/script>/g)) {
    for (const p of m[1].match(/\[PLACEHOLDER[^\]]*\]/g) ?? []) inJsonLd.add(p);
  }
}

// Placeholders on every page (header/footer/NAP) are listed once as "Global".
const all = [...perPage.values()];
const global = [...all[0]].filter((t) => all.every((s) => s.has(t)));
let md = `### Global (header, footer, NAP block: every page)\n\n${global.map((t) => `- ${t}`).join('\n')}\n`;
for (const [page, set] of perPage) {
  const own = [...set].filter((t) => !global.includes(t));
  if (own.length) md += `\n### ${page}\n\n${own.map((t) => `- ${t}`).join('\n')}\n`;
}
const hidden = [...inJsonLd].filter((t) => !visible.has(t));
if (hidden.length) md += `\n### Structured data only (JSON-LD, not visible on page)\n\n${hidden.map((t) => `- ${t}`).join('\n')}\n`;

const total = new Set([...visible, ...hidden]).size;
const readmeUrl = new URL('../README.md', import.meta.url);
const readme = readFileSync(readmeUrl, 'utf8');
const updated = readme.replace(
  /<!-- PLACEHOLDERS:START -->[\s\S]*<!-- PLACEHOLDERS:END -->/,
  `<!-- PLACEHOLDERS:START -->\n_Generated by \`npm run report:placeholders\`. ${total} distinct placeholders._\n\n${md}\n<!-- PLACEHOLDERS:END -->`,
);
writeFileSync(readmeUrl, updated);
console.log(`Wrote ${total} distinct placeholders across ${perPage.size} pages into README.md`);
